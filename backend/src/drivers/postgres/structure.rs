//! Reads a table's or view's structure from the system catalogs and rebuilds its DDL.
//! PostgreSQL has no `SHOW CREATE TABLE`, so the script is assembled from the
//! server's own `pg_get_*def` functions, the way `pg_dump` does.

use sqlx::Connection as _;
use sqlx::postgres::PgConnection;

use super::connect;
use crate::connections::model::Connection;
use crate::drivers::{ColumnInfo, ForeignKey, IndexInfo, ObjectKind, TableRef, TableStructure, TriggerInfo};
use crate::error::Result;

pub async fn table_structure(
    connection: &Connection,
    password: Option<&str>,
    table: &TableRef,
) -> Result<TableStructure> {
    let mut conn = connect(connection, password, Some(&table.database)).await?;
    // `regclass` resolves the name once per query; quoting keeps odd names intact.
    let relation: String = sqlx::query_scalar("SELECT format('%I.%I', $1::text, $2::text)")
        .bind(&table.schema)
        .bind(&table.name)
        .fetch_one(&mut conn)
        .await?;

    let (relkind, row_estimate, data_bytes, index_bytes, comment): (String, i64, i64, i64, Option<String>) =
        sqlx::query_as(
            "SELECT relkind::text, reltuples::int8, pg_table_size(oid), pg_indexes_size(oid),
                    obj_description(oid, 'pg_class')
             FROM pg_class WHERE oid = $1::regclass",
        )
        .bind(&relation)
        .fetch_one(&mut conn)
        .await?;

    let columns = columns(&mut conn, &relation).await?;
    let indexes = indexes(&mut conn, &relation).await?;
    let foreign_keys = foreign_keys(&mut conn, &relation).await?;
    let triggers = triggers(&mut conn, &relation).await?;
    let is_view = matches!(relkind.as_str(), "v" | "m");
    let ddl = if is_view {
        view_ddl(&mut conn, &relation, &relkind, &comment, &columns).await?
    } else {
        table_ddl(&mut conn, &relation, &comment, &columns, &indexes).await?
    };
    conn.close().await?;

    Ok(TableStructure {
        kind: if is_view { ObjectKind::View } else { ObjectKind::Table },
        // -1 means the table was never analyzed.
        row_estimate: (row_estimate >= 0).then_some(row_estimate),
        data_bytes,
        index_bytes,
        comment,
        columns: columns.into_iter().map(|c| c.info).collect(),
        indexes: indexes.into_iter().map(|i| i.info).collect(),
        ddl: with_triggers(ddl, &triggers),
        foreign_keys,
        triggers,
    })
}

struct CatalogColumn {
    info: ColumnInfo,
    /// The name quoted only where SQL needs it.
    quoted_name: String,
    /// How the default appears in `CREATE TABLE`, e.g. `DEFAULT 0`.
    default_clause: Option<String>,
}

async fn columns(conn: &mut PgConnection, relation: &str) -> Result<Vec<CatalogColumn>> {
    type Row = (String, String, String, bool, Option<String>, String, String, Option<String>);
    let rows: Vec<Row> = sqlx::query_as(
        "SELECT a.attname::text, quote_ident(a.attname), format_type(a.atttypid, a.atttypmod), NOT a.attnotnull,
                pg_get_expr(d.adbin, d.adrelid), a.attidentity::text, a.attgenerated::text,
                col_description(a.attrelid, a.attnum)
         FROM pg_attribute a
         LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
         WHERE a.attrelid = $1::regclass AND a.attnum > 0 AND NOT a.attisdropped
         ORDER BY a.attnum",
    )
    .bind(relation)
    .fetch_all(conn)
    .await?;

    Ok(rows
        .into_iter()
        .map(|(name, quoted_name, data_type, nullable, expression, identity, generated, comment)| {
            let default_clause = match (identity.as_str(), generated.as_str(), expression) {
                ("a", _, _) => Some("GENERATED ALWAYS AS IDENTITY".to_string()),
                ("d", _, _) => Some("GENERATED BY DEFAULT AS IDENTITY".to_string()),
                (_, "s", Some(expression)) => Some(format!("GENERATED ALWAYS AS ({expression}) STORED")),
                (_, "v", Some(expression)) => Some(format!("GENERATED ALWAYS AS ({expression}) VIRTUAL")),
                (_, _, Some(expression)) => Some(format!("DEFAULT {expression}")),
                _ => None,
            };
            let default = default_clause.as_ref().map(|clause| clause.trim_start_matches("DEFAULT ").to_string());
            CatalogColumn {
                info: ColumnInfo { name, data_type, nullable, default, comment },
                quoted_name,
                default_clause,
            }
        })
        .collect())
}

struct CatalogIndex {
    info: IndexInfo,
    definition: String,
    /// Created by a PRIMARY KEY, UNIQUE or EXCLUDE constraint rather than on its own.
    backs_constraint: bool,
}

async fn indexes(conn: &mut PgConnection, relation: &str) -> Result<Vec<CatalogIndex>> {
    type Row = (String, String, bool, bool, Vec<String>, Option<String>, i64, String, bool);
    let rows: Vec<Row> = sqlx::query_as(
        "SELECT i.relname::text, am.amname::text, x.indisunique, x.indisprimary,
                ARRAY(SELECT pg_get_indexdef(x.indexrelid, k, true) FROM generate_series(1, x.indnkeyatts) k),
                pg_get_expr(x.indpred, x.indrelid, true), pg_relation_size(x.indexrelid), pg_get_indexdef(x.indexrelid),
                EXISTS (SELECT 1 FROM pg_constraint c
                        WHERE c.conindid = x.indexrelid AND c.conrelid = x.indrelid AND c.contype IN ('p', 'u', 'x'))
         FROM pg_index x
         JOIN pg_class i ON i.oid = x.indexrelid
         JOIN pg_am am ON am.oid = i.relam
         WHERE x.indrelid = $1::regclass
         ORDER BY x.indisprimary DESC, i.relname",
    )
    .bind(relation)
    .fetch_all(conn)
    .await?;

    Ok(rows
        .into_iter()
        .map(|(name, method, unique, primary, columns, condition, bytes, definition, backs_constraint)| CatalogIndex {
            info: IndexInfo { name, method, unique, primary, columns, condition, bytes },
            definition,
            backs_constraint,
        })
        .collect())
}

async fn foreign_keys(conn: &mut PgConnection, relation: &str) -> Result<Vec<ForeignKey>> {
    type Row = (String, Vec<String>, String, Vec<String>, String, String);
    let rows: Vec<Row> = sqlx::query_as(
        "SELECT c.conname::text,
                ARRAY(SELECT a.attname::text FROM unnest(c.conkey) WITH ORDINALITY k(num, ord)
                      JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = k.num ORDER BY k.ord),
                c.confrelid::regclass::text,
                ARRAY(SELECT a.attname::text FROM unnest(c.confkey) WITH ORDINALITY k(num, ord)
                      JOIN pg_attribute a ON a.attrelid = c.confrelid AND a.attnum = k.num ORDER BY k.ord),
                c.confupdtype::text, c.confdeltype::text
         FROM pg_constraint c
         WHERE c.conrelid = $1::regclass AND c.contype = 'f'
         ORDER BY c.conname",
    )
    .bind(relation)
    .fetch_all(conn)
    .await?;

    Ok(rows
        .into_iter()
        .map(|(name, columns, referenced_table, referenced_columns, on_update, on_delete)| ForeignKey {
            name,
            columns,
            referenced_table,
            referenced_columns,
            on_update: action_name(&on_update).to_string(),
            on_delete: action_name(&on_delete).to_string(),
        })
        .collect())
}

/// Spells out `pg_constraint`'s one-letter referential action codes.
fn action_name(code: &str) -> &'static str {
    match code {
        "r" => "RESTRICT",
        "c" => "CASCADE",
        "n" => "SET NULL",
        "d" => "SET DEFAULT",
        _ => "NO ACTION",
    }
}

async fn triggers(conn: &mut PgConnection, relation: &str) -> Result<Vec<TriggerInfo>> {
    let rows: Vec<(String, bool, String)> = sqlx::query_as(
        "SELECT tgname::text, tgenabled <> 'D', pg_get_triggerdef(oid, true)
         FROM pg_trigger WHERE tgrelid = $1::regclass AND NOT tgisinternal
         ORDER BY tgname",
    )
    .bind(relation)
    .fetch_all(conn)
    .await?;
    Ok(rows.into_iter().map(|(name, enabled, definition)| TriggerInfo { name, enabled, definition }).collect())
}

async fn table_ddl(
    conn: &mut PgConnection,
    relation: &str,
    comment: &Option<String>,
    columns: &[CatalogColumn],
    indexes: &[CatalogIndex],
) -> Result<String> {
    // NOT NULL constraints (contype 'n' since PostgreSQL 18) are written on the columns.
    let constraints: Vec<(String, String)> = sqlx::query_as(
        "SELECT quote_ident(conname), pg_get_constraintdef(oid, true)
         FROM pg_constraint
         WHERE conrelid = $1::regclass AND contype IN ('p', 'u', 'c', 'f', 'x')
         ORDER BY array_position(ARRAY['p', 'u', 'c', 'f', 'x'], contype::text), conname",
    )
    .bind(relation)
    .fetch_all(conn)
    .await?;

    let column_lines = columns.iter().map(|c| {
        let mut line = format!("    {} {}", c.quoted_name, c.info.data_type);
        if let Some(clause) = &c.default_clause {
            line.push_str(&format!(" {clause}"));
        }
        if !c.info.nullable {
            line.push_str(" NOT NULL");
        }
        line
    });
    let constraint_lines = constraints.iter().map(|(name, definition)| format!("    CONSTRAINT {name} {definition}"));
    let body: Vec<String> = column_lines.chain(constraint_lines).collect();

    let mut sections = vec![format!("CREATE TABLE {relation} (\n{}\n);", body.join(",\n"))];
    let standalone: Vec<String> =
        indexes.iter().filter(|i| !i.backs_constraint).map(|i| format!("{};", i.definition)).collect();
    if !standalone.is_empty() {
        sections.push(standalone.join("\n"));
    }
    sections.extend(comments_section(relation, "TABLE", comment, columns));
    Ok(sections.join("\n\n"))
}

async fn view_ddl(
    conn: &mut PgConnection,
    relation: &str,
    relkind: &str,
    comment: &Option<String>,
    columns: &[CatalogColumn],
) -> Result<String> {
    let definition: String =
        sqlx::query_scalar("SELECT pg_get_viewdef($1::regclass, true)").bind(relation).fetch_one(conn).await?;
    let (kind, object) = if relkind == "m" { ("MATERIALIZED VIEW", "MATERIALIZED VIEW") } else { ("VIEW", "VIEW") };
    let query = definition.trim().trim_end_matches(';');
    let mut sections = vec![format!("CREATE {kind} {relation} AS\n{query};")];
    sections.extend(comments_section(relation, object, comment, columns));
    Ok(sections.join("\n\n"))
}

fn comments_section(
    relation: &str,
    object: &str,
    comment: &Option<String>,
    columns: &[CatalogColumn],
) -> Option<String> {
    let table = comment.iter().map(|text| format!("COMMENT ON {object} {relation} IS {};", quote_literal(text)));
    let columns = columns.iter().filter_map(|c| {
        let text = c.info.comment.as_ref()?;
        Some(format!("COMMENT ON COLUMN {relation}.{} IS {};", c.quoted_name, quote_literal(text)))
    });
    let lines: Vec<String> = table.chain(columns).collect();
    (!lines.is_empty()).then(|| lines.join("\n"))
}

fn with_triggers(ddl: String, triggers: &[TriggerInfo]) -> String {
    if triggers.is_empty() {
        return ddl;
    }
    let definitions: Vec<String> = triggers.iter().map(|t| format!("{};", t.definition)).collect();
    format!("{ddl}\n\n{}", definitions.join("\n"))
}

fn quote_literal(text: &str) -> String {
    format!("'{}'", text.replace('\'', "''"))
}

#[cfg(test)]
mod tests {
    use super::super::tests::{PASSWORD, local};
    use super::*;

    const SETUP: &str = "
        DROP SCHEMA IF EXISTS dbforge_structure CASCADE;
        CREATE SCHEMA dbforge_structure;
        CREATE TABLE dbforge_structure.customers (id int PRIMARY KEY);
        CREATE TABLE dbforge_structure.orders (
            id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
            customer_id int NOT NULL REFERENCES dbforge_structure.customers (id) ON DELETE CASCADE,
            total numeric(10,2) DEFAULT 0,
            \"Note\" text,
            CONSTRAINT positive_total CHECK (total >= 0)
        );
        CREATE INDEX orders_note_idx ON dbforge_structure.orders (lower(\"Note\"));
        CREATE UNIQUE INDEX orders_one_free_per_customer ON dbforge_structure.orders (customer_id) WHERE total = 0;
        COMMENT ON TABLE dbforge_structure.orders IS 'Customer''s orders';
        COMMENT ON COLUMN dbforge_structure.orders.\"Note\" IS 'Free text';
        CREATE FUNCTION dbforge_structure.touch() RETURNS trigger LANGUAGE plpgsql AS 'BEGIN RETURN NEW; END';
        CREATE TRIGGER orders_touch BEFORE UPDATE ON dbforge_structure.orders
            FOR EACH ROW EXECUTE FUNCTION dbforge_structure.touch();
        CREATE VIEW dbforge_structure.big_orders AS SELECT id, total FROM dbforge_structure.orders WHERE total > 100;";

    fn table(name: &str) -> TableRef {
        TableRef { database: "shop".into(), schema: "dbforge_structure".into(), name: name.into() }
    }

    async fn run(sql: &str) {
        let mut conn = connect(&local(), PASSWORD, None).await.unwrap();
        sqlx::raw_sql(sqlx::AssertSqlSafe(sql)).execute(&mut conn).await.unwrap();
    }

    #[test]
    fn action_codes_are_spelled_out() {
        assert_eq!(action_name("a"), "NO ACTION");
        assert_eq!(action_name("c"), "CASCADE");
        assert_eq!(action_name("n"), "SET NULL");
    }

    #[test]
    fn literals_escape_quotes() {
        assert_eq!(quote_literal("it's"), "'it''s'");
    }

    #[tokio::test]
    #[ignore = "needs a local PostgreSQL on port 55432"]
    async fn reads_the_structure_and_rebuilds_it_from_the_ddl() {
        run(SETUP).await;
        let orders = table_structure(&local(), PASSWORD, &table("orders")).await.unwrap();

        assert_eq!(orders.kind, ObjectKind::Table);
        assert_eq!(orders.comment.as_deref(), Some("Customer's orders"));
        let columns: Vec<_> = orders
            .columns
            .iter()
            .map(|c| (c.name.as_str(), c.data_type.as_str(), c.nullable, c.default.as_deref()))
            .collect();
        assert_eq!(
            columns,
            [
                ("id", "integer", false, Some("GENERATED ALWAYS AS IDENTITY")),
                ("customer_id", "integer", false, None),
                ("total", "numeric(10,2)", true, Some("0")),
                ("Note", "text", true, None),
            ]
        );

        let indexes: Vec<_> = orders
            .indexes
            .iter()
            .map(|i| (i.name.as_str(), i.unique, i.columns.join(", "), i.condition.as_deref()))
            .collect();
        assert_eq!(
            indexes,
            [
                ("orders_pkey", true, "id".into(), None),
                ("orders_note_idx", false, "lower(\"Note\")".into(), None),
                ("orders_one_free_per_customer", true, "customer_id".into(), Some("total = 0::numeric")),
            ]
        );

        let [fk] = orders.foreign_keys.as_slice() else { panic!("{:?}", orders.foreign_keys) };
        assert_eq!(fk.columns, ["customer_id"]);
        assert_eq!(fk.referenced_table, "dbforge_structure.customers");
        assert_eq!(fk.referenced_columns, ["id"]);
        assert_eq!((fk.on_update.as_str(), fk.on_delete.as_str()), ("NO ACTION", "CASCADE"));

        let [trigger] = orders.triggers.as_slice() else { panic!("{:?}", orders.triggers) };
        assert_eq!(trigger.name, "orders_touch");
        assert!(trigger.enabled);

        let view = table_structure(&local(), PASSWORD, &table("big_orders")).await.unwrap();
        assert_eq!(view.kind, ObjectKind::View);
        assert!(view.ddl.starts_with("CREATE VIEW dbforge_structure.big_orders AS\n"), "{}", view.ddl);

        // The DDL is only useful if it rebuilds the same table.
        run("DROP TABLE dbforge_structure.orders CASCADE").await;
        run(&orders.ddl).await;
        let rebuilt = table_structure(&local(), PASSWORD, &table("orders")).await.unwrap();
        assert_eq!(rebuilt.ddl, orders.ddl);

        run("DROP SCHEMA dbforge_structure CASCADE").await;
    }
}
